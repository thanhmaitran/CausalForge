"""CausalForge HTTP API. Thin: routing + validation only; all statistics live in services/."""
from __future__ import annotations

import os

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel

from causalforge_api.services import engine
from causalforge_api.services.store import Store

app = FastAPI(title="CausalForge API", version="1.0.0",
              description="Causal Inference and Decision Intelligence Platform")
store = Store(os.environ.get("CAUSALFORGE_DB", ":memory:"))


class DatasetSpec(BaseModel):
    spec: dict
    post_treatment: list[str] | None = None


class GraphIn(BaseModel):
    graph_json: str
    treatment: str
    outcome: str


class EstimateIn(BaseModel):
    spec: dict
    estimator: str = "aipw"
    seed: int = 0


class SensIn(BaseModel):
    spec: dict
    q: float = 1.0
    alpha: float = 0.05


class PolicyIn(BaseModel):
    spec: dict
    budget: float = 0.2


def _guard(fn, *a, **k):
    try:
        return fn(*a, **k)
    except (ValueError, KeyError) as e:
        raise HTTPException(status_code=422, detail=str(e)) from e


@app.get("/health")
def health():
    return {"status": "healthy", "service": "causalforge-api"}


@app.get("/datasets")
def datasets():
    return engine.list_datasets()


@app.post("/datasets/validate")
def validate(b: DatasetSpec):
    return _guard(engine.validate, b.spec, b.post_treatment)


@app.post("/graphs")
def create_graph(b: GraphIn):
    _guard(engine.identify, b.graph_json, b.treatment, b.outcome)  # validates DAG
    return {"id": store.add_graph(b.graph_json, b.treatment, b.outcome)}


@app.get("/graphs/{gid}")
def get_graph(gid: int):
    g = store.get_graph(gid)
    if g is None:
        raise HTTPException(404, "graph not found")
    return g


@app.post("/causal/identify")
def identify(b: GraphIn):
    return _guard(engine.identify, b.graph_json, b.treatment, b.outcome)


@app.post("/causal/estimate")
def estimate(b: EstimateIn):
    res = _guard(engine.estimate, b.spec, b.estimator)
    res["experiment_id"] = store.add_experiment(b.estimator, res["estimand"], b.spec, b.seed, res)
    return res


@app.post("/causal/sensitivity")
def sensitivity(b: SensIn):
    return _guard(engine.sensitivity, b.spec, b.q, b.alpha)


@app.post("/experiments")
def create_experiment(b: EstimateIn):
    return estimate(b)


@app.get("/experiments/{eid}")
def get_experiment(eid: int):
    e = store.get_experiment(eid)
    if e is None:
        raise HTTPException(404, "experiment not found")
    return e


@app.get("/experiments/{eid}/results")
def experiment_results(eid: int):
    return get_experiment(eid)


@app.post("/policies/evaluate")
def policies(b: PolicyIn):
    return _guard(engine.evaluate_policy, b.spec, b.budget)


@app.get("/reports/{rid}")
def report(rid: int):
    e = store.get_experiment(rid)
    if e is None:
        raise HTTPException(404, "report not found")
    return {"experiment": e, "note": "Full reports are generated by scripts/generate_report.py"}
